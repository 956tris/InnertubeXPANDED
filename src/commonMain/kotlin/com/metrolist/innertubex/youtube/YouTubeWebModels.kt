package com.metrolist.innertubex.youtube

data class YouTubeVideo(
    val id: String,
    val title: String,
    val channelName: String,
    val channelId: String? = null,
    val durationSeconds: Long? = null,
    val viewCountText: String? = null,
    val publishedText: String? = null,
    val thumbnailUrl: String = "",
    val isLive: Boolean = false,
    val isShort: Boolean = false,
    val is4k: Boolean = false,
    val likeStatus: String? = null,
)

data class YouTubeChannelSummary(
    val id: String,
    val title: String,
    val handle: String? = null,
    val subscriberText: String? = null,
    val avatarUrl: String = "",
)

data class YouTubePlaylistSummary(
    val id: String,
    val title: String,
    val author: String = "",
    val videoCountText: String? = null,
    val thumbnailUrl: String = "",
)

data class YouTubeFeedItem(
    val video: YouTubeVideo? = null,
    val channel: YouTubeChannelSummary? = null,
    val playlist: YouTubePlaylistSummary? = null,
)

data class YouTubeShelf(
    val title: String,
    val items: List<YouTubeFeedItem>,
    val isShorts: Boolean = false,
)

data class YouTubeFeedPage(
    val shelves: List<YouTubeShelf>,
    val items: List<YouTubeFeedItem>,
    val continuation: String? = null,
)

data class YouTubeChannelPage(
    val id: String,
    val title: String,
    val handle: String? = null,
    val description: String? = null,
    val subscriberText: String? = null,
    val avatarUrl: String = "",
    val bannerUrl: String = "",
    val videos: List<YouTubeVideo>,
    val playlists: List<YouTubePlaylistSummary>,
    val continuation: String? = null,
)

data class YouTubePlaylistPage(
    val id: String,
    val title: String,
    val author: String = "",
    val description: String? = null,
    val thumbnailUrl: String = "",
    val videos: List<YouTubeVideo>,
    val continuation: String? = null,
)

data class YouTubeChapter(
    val title: String,
    val startMs: Long,
)

data class YouTubeNextPage(
    val video: YouTubeVideo? = null,
    val related: List<YouTubeVideo> = emptyList(),
    val playlistVideos: List<YouTubeVideo> = emptyList(),
    val chapters: List<YouTubeChapter> = emptyList(),
    val continuation: String? = null,
)

data class YouTubeCaptionTrack(
    val languageCode: String,
    val name: String,
    val baseUrl: String,
    val isAutoGenerated: Boolean = false,
)

data class YouTubeCaptionLine(
    val startMs: Long,
    val durationMs: Long,
    val text: String,
)

data class YouTubeAccountInfo(
    val name: String,
    val handle: String? = null,
    val avatarUrl: String? = null,
)

enum class YouTubeSearchFilter(
    val params: String?,
) {
    ALL(null),
    VIDEO("EgIQAQ%3D%3D"),
    CHANNEL("EgIQAg%3D%3D"),
    PLAYLIST("EgIQAw%3D%3D"),
    LIVE("EgJAAQ%3D%3D"),
    FOUR_K("EgJwAQ%3D%3D"),
}
